#!/usr/bin/env node
/**
 * StrongBox price-list generator.
 *
 *   node packages/pricing/build.mjs
 *
 * Reads packages/pricing/pricing.json — the DEFAULT prices — and writes:
 *   - web/lib/pricing.g.ts                   (DEFAULT_PRICES)
 *   - app/lib/core/constants/price_list.g.dart  (PriceList.catalog)
 *   - functions/src/default-rates.g.json        (monthly invoice fallback rates)
 *
 * Live prices are set by admins in the app and stored in Firestore
 * `priceLists/{tenantId}`; both apps fall back to these defaults until then.
 *
 * Both outputs are committed so deploys need no generator step of their own,
 * but CI runs this first so a stale committed file is caught.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const pricing = JSON.parse(readFileSync(resolve(here, "pricing.json"), "utf8"));

const BANNER = "GENERATED by packages/pricing/build.mjs — do not edit by hand.";

/* ---- TypeScript ------------------------------------------------------ */

function buildTs() {
  const { $comment, ...data } = pricing;
  return [
    `// ${BANNER}`,
    "// See packages/pricing/pricing.json. These are only the defaults — the site",
    "// reads live prices from Firestore via getPrices() in lib/prices.ts.",
    "",
    `export const DEFAULT_PRICES = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

/* ---- Dart ------------------------------------------------------------ */

const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const dbl = (n) => (Number.isInteger(n) ? `${n}.0` : `${n}`);

function buildDart() {
  const L = [];
  const active = (e) => (e.active === false ? ", active: false" : "");
  L.push(`// ${BANNER}`);
  L.push("// See packages/pricing/pricing.json.");
  L.push("// ignore_for_file: type=lint");
  L.push("");
  L.push("import '../models/price_catalog.dart';");
  L.push("");
  L.push("/// The default price list — what the app and the website use until an");
  L.push("/// admin first saves prices (Admin → Pricing → Firestore `priceLists`).");
  L.push("class PriceList {");
  L.push("  PriceList._();");
  L.push("");
  L.push("  static const catalog = PriceCatalog(");
  L.push("    boxes: [");
  for (const b of pricing.boxes) {
    L.push(`      BoxPrice(id: ${str(b.id)}, label: ${str(b.label)}, description: ${str(b.desc)}, monthlyZar: ${num(b.price)}${active(b)}),`);
  }
  L.push("    ],");
  L.push("    looseItemCategories: [");
  for (const c of pricing.looseItemCategories) L.push(`      ${str(c)},`);
  L.push("    ],");
  L.push("    looseItems: [");
  for (const i of pricing.looseItems) {
    L.push(`      LooseItemPrice(id: ${str(i.id)}, name: ${str(i.name)}, category: ${str(i.category)}, icon: ${str(i.icon)}, monthlyZar: ${num(i.price)}${active(i)}),`);
  }
  L.push("    ],");
  L.push("    itemIcons: [");
  for (const icon of pricing.itemIcons) L.push(`      ${str(icon)},`);
  L.push("    ],");
  L.push("    vehicles: [");
  for (const v of pricing.vehicles) {
    L.push(`      VehiclePrice(id: ${str(v.id)}, label: ${str(v.label)}, description: ${str(v.desc)}, capacityM3: ${dbl(v.capacityM3)}, onceOffZar: ${num(v.price)}, recommended: ${v.recommended}, icon: ${str(v.icon)}${active(v)}),`);
  }
  L.push("    ],");
  L.push("  );");
  L.push("}");
  L.push("");
  return L.join("\n");
}

/* ---- Cloud Functions -------------------------------------------------- */

// The monthly invoice run only needs each box / loose item's default rate,
// for units registered before their rate was recorded.
function buildFunctionsJson() {
  const rates = {};
  for (const b of pricing.boxes) rates[b.id] = b.price;
  for (const i of pricing.looseItems) rates[i.id] = i.price;
  return JSON.stringify({ $comment: BANNER, monthlyZar: rates }, null, 2) + "\n";
}

/* ---- write ----------------------------------------------------------- */

const outputs = [
  ["web/lib/pricing.g.ts", buildTs()],
  ["app/lib/core/constants/price_list.g.dart", buildDart()],
  ["functions/src/default-rates.g.json", buildFunctionsJson()],
];

for (const [rel, content] of outputs) {
  const path = resolve(repoRoot, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log("wrote", rel);
}
