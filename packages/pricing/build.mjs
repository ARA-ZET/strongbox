#!/usr/bin/env node
/**
 * StrongBox price-list generator.
 *
 *   node packages/pricing/build.mjs
 *
 * Reads packages/pricing/pricing.json and writes:
 *   - web/lib/pricing.g.ts                   (BOX_TYPES, LOOSE_ITEMS, VEHICLES …)
 *   - app/lib/core/constants/price_list.g.dart  (PriceList class)
 *
 * Both outputs are committed so deploys need no generator step of their own,
 * but CI runs this first so a stale committed file is caught.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const pricing = JSON.parse(readFileSync(resolve(here, "pricing.json"), "utf8"));

const BANNER = "GENERATED by packages/pricing/build.mjs — do not edit by hand.";

/* ---- TypeScript ------------------------------------------------------ */

function buildTs() {
  const block = (name, value) =>
    `export const ${name} = ${JSON.stringify(value, null, 2)} as const;`;
  return [
    `// ${BANNER}`,
    "// See packages/pricing/pricing.json.",
    "",
    block("BOX_TYPES", pricing.boxes),
    "",
    block("LOOSE_ITEM_CATEGORIES", pricing.looseItemCategories),
    "",
    block("LOOSE_ITEMS", pricing.looseItems),
    "",
    "// `recommended` is declared on every entry so the union stays uniform — the",
    "// calculator reads `v.recommended` directly.",
    block("VEHICLES", pricing.vehicles),
    "",
  ].join("\n");
}

/* ---- Dart ------------------------------------------------------------ */

const str = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const dbl = (n) => (Number.isInteger(n) ? `${n}.0` : `${n}`);

function buildDart() {
  const L = [];
  L.push(`// ${BANNER}`);
  L.push("// See packages/pricing/pricing.json.");
  L.push("// ignore_for_file: type=lint");
  L.push("");
  L.push("/// A storage box size, charged per box per month.");
  L.push("class BoxPrice {");
  L.push("  const BoxPrice({required this.id, required this.label, required this.description, required this.monthlyZar});");
  L.push("  final String id;");
  L.push("  final String label;");
  L.push("  final String description;");
  L.push("  final int monthlyZar;");
  L.push("}");
  L.push("");
  L.push("/// A loose (unboxed) item, charged per item per month.");
  L.push("class LooseItemPrice {");
  L.push("  const LooseItemPrice({required this.id, required this.name, required this.category, required this.icon, required this.monthlyZar});");
  L.push("  final String id;");
  L.push("  final String name;");
  L.push("  final String category;");
  L.push("");
  L.push("  /// Material Symbols name used by the website.");
  L.push("  final String icon;");
  L.push("  final int monthlyZar;");
  L.push("}");
  L.push("");
  L.push("/// A pickup vehicle, charged once per collection.");
  L.push("class VehiclePrice {");
  L.push("  const VehiclePrice({required this.id, required this.label, required this.description, required this.capacityM3, required this.onceOffZar, required this.recommended});");
  L.push("  final String id;");
  L.push("  final String label;");
  L.push("  final String description;");
  L.push("  final double capacityM3;");
  L.push("  final int onceOffZar;");
  L.push("  final bool recommended;");
  L.push("}");
  L.push("");
  L.push("/// The price list shared with the marketing site (web/).");
  L.push("class PriceList {");
  L.push("  PriceList._();");
  L.push("");
  L.push("  static const boxes = <BoxPrice>[");
  for (const b of pricing.boxes) {
    L.push(`    BoxPrice(id: ${str(b.id)}, label: ${str(b.label)}, description: ${str(b.desc)}, monthlyZar: ${num(b.price)}),`);
  }
  L.push("  ];");
  L.push("");
  L.push("  static const looseItemCategories = <String>[");
  for (const c of pricing.looseItemCategories) L.push(`    ${str(c)},`);
  L.push("  ];");
  L.push("");
  L.push("  static const looseItems = <LooseItemPrice>[");
  for (const i of pricing.looseItems) {
    L.push(`    LooseItemPrice(id: ${str(i.id)}, name: ${str(i.name)}, category: ${str(i.category)}, icon: ${str(i.icon)}, monthlyZar: ${num(i.price)}),`);
  }
  L.push("  ];");
  L.push("");
  L.push("  static const vehicles = <VehiclePrice>[");
  for (const v of pricing.vehicles) {
    L.push(`    VehiclePrice(id: ${str(v.id)}, label: ${str(v.label)}, description: ${str(v.desc)}, capacityM3: ${dbl(v.capacityM3)}, onceOffZar: ${num(v.price)}, recommended: ${v.recommended}),`);
  }
  L.push("  ];");
  L.push("");
  L.push("}");
  L.push("");
  return L.join("\n");
}

/* ---- write ----------------------------------------------------------- */

const outputs = [
  ["web/lib/pricing.g.ts", buildTs()],
  ["app/lib/core/constants/price_list.g.dart", buildDart()],
];

for (const [rel, content] of outputs) {
  const path = resolve(repoRoot, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log("wrote", rel);
}
