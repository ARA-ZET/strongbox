#!/usr/bin/env node
/**
 * StrongBox design-token generator.
 *
 *   node packages/tokens/build.mjs
 *
 * Reads packages/tokens/tokens.json and writes:
 *   - app/lib/core/theme/tokens.g.dart   (DesignTokens class)
 *   - web/lib/tokens.g.ts                 (tokens object + :root CSS string)
 *
 * Both outputs are committed so CI / deploys need no generator step of their own,
 * but the workflow runs this first and fails if anything is stale.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const tokens = JSON.parse(readFileSync(resolve(here, "tokens.json"), "utf8"));

const BANNER = "GENERATED by packages/tokens/build.mjs — do not edit by hand.";

/* ---- helpers ---------------------------------------------------------- */

// "#RRGGBB" or "#RRGGBBAA"  ->  Dart 0xAARRGGBB literal
function dartColor(hex) {
  const h = hex.replace("#", "");
  const rgb = h.slice(0, 6);
  const a = h.length === 8 ? h.slice(6, 8) : "FF";
  return `0x${a}${rgb}`.toUpperCase().replace("0X", "0x");
}

// "#RRGGBBAA" -> "rgba(r, g, b, a)"  /  "#RRGGBB" -> "#RRGGBB"
function cssColor(hex) {
  const h = hex.replace("#", "");
  if (h.length !== 8) return `#${h}`;
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  const a = (parseInt(h.slice(6, 8), 16) / 255).toFixed(3).replace(/0+$/, "").replace(/\.$/, "");
  return `rgba(${r}, ${g}, ${b}, ${a})`;
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/* ---- Dart ------------------------------------------------------------- */

function buildDart() {
  const L = [];
  L.push(`// ${BANNER}`);
  L.push("// ignore_for_file: type=lint");
  L.push("");
  L.push("import 'package:flutter/widgets.dart';");
  L.push("");
  L.push("/// Cross-platform design tokens shared with the marketing site (web/).");
  L.push("/// See packages/tokens/tokens.json.");
  L.push("class DesignTokens {");
  L.push("  DesignTokens._();");
  L.push("");
  for (const [k, v] of Object.entries(tokens.color)) {
    L.push(`  static const Color ${k} = Color(${dartColor(v)});`);
  }
  L.push("");
  for (const [k, v] of Object.entries(tokens.space)) {
    L.push(`  static const double space${cap(k)} = ${v.toFixed(1)};`);
  }
  L.push("");
  for (const [k, v] of Object.entries(tokens.radius)) {
    L.push(`  static const double radius${cap(k)} = ${v.toFixed(1)};`);
  }
  L.push("");
  L.push(`  static const String fontFamily = ${JSON.stringify(tokens.font.family)};`);
  for (const [k, v] of Object.entries(tokens.font.size)) {
    L.push(`  static const double font${cap(k)} = ${v.toFixed(1)};`);
  }
  L.push("}");
  L.push("");
  return L.join("\n");
}

const cap = (s) => s[0].toUpperCase() + s.slice(1);

/* ---- TypeScript + CSS ----------------------------------------------- */

function buildTs() {
  const cssVars = [];
  for (const [k, v] of Object.entries(tokens.color)) cssVars.push(`  --color-${kebab(k)}: ${cssColor(v)};`);
  for (const [k, v] of Object.entries(tokens.space)) cssVars.push(`  --space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.radius)) cssVars.push(`  --radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.font.size)) cssVars.push(`  --font-${k}: ${v}px;`);

  return [
    `// ${BANNER}`,
    `// See packages/tokens/tokens.json.`,
    "",
    `export const tokens = ${JSON.stringify(tokens, null, 2)} as const;`,
    "",
    `export const cssVariables = \`:root {`,
    cssVars.join("\n"),
    `}\`;`,
    "",
  ].join("\n");
}

/* ---- write ---------------------------------------------------------- */

const outputs = [
  ["app/lib/core/theme/tokens.g.dart", buildDart()],
  ["web/lib/tokens.g.ts", buildTs()],
];

for (const [rel, content] of outputs) {
  const path = resolve(repoRoot, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log("wrote", rel);
}
