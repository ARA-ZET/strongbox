const inter = Inter({
  subsets: ["latin"],
  variable: "--font-inter",
  display: "swap",
});

/**
 * Site-wide defaults only.
 *
 * Deliberately no `alternates.canonical` here: Next shallow-merges metadata,
 * so a canonical declared at this level is inherited verbatim by every page
 * that does not restate one — which had eight routes declaring themselves
 * duplicates of the homepage. Canonicals now come from `pageMeta` in
 * `lib/seo.ts`, which cannot be called without a path. For the same reason
 * `openGraph` carries no title or description here; per-page values would
 * otherwise never reach the social card.
 */
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: {
    default: "StrongBox | Storage Collected From Your Door in Cape Town",
    template: "%s | StrongBox",
  },
  description:
    "StrongBox collects your boxes and furniture from your door anywhere in Cape Town, stores them in a monitored facility, and brings them back when you ask. Monthly billing, no lock-in.",
  applicationName: SITE_NAME,
  authors: [{ name: SITE_NAME, url: SITE_URL }],
  creator: SITE_NAME,
  publisher: SITE_NAME,
  category: "Storage and logistics",
  openGraph: {
    type: "website",
    locale: "en_ZA",
    url: SITE_URL,
    siteName: SITE_NAME,
  },
  twitter: { card: "summary_large_image" },
  robots: {
    index: true,
    follow: true,
    googleBot: {
      index: true,
      follow: true,
      "max-image-preview": "large",
      "max-snippet": -1,
      "max-video-preview": -1,
    },
  },
  formatDetection: { telephone: true, address: true, email: true },
  /*
   * Search Console site verification. Set NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION
   * in apphosting.yaml to the token Google gives you under the "HTML tag"
   * method; the tag is omitted entirely when it is unset, which is what you
   * want in preview environments. Verification is the gate on submitting the
   * sitemap and on seeing any of the query data at all, so nothing else here
   * pays off until this is filled in.
   */
  verification: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION
    ? { google: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION }
    : undefined,
};

/**
 * The icon webfont, subsetted to the glyphs the site renders.
 *
 * Unsubsetted this request is 3.97 MB — render-blocking, on every page, and
 * comfortably the heaviest thing the site shipped. `icon_names` brings it to
 * roughly 89 KB. The list is generated by `scripts/collect-icons.mjs`; run it
 * after adding an icon, or the new glyph renders as its own literal name.
 *
 * `display=block` rather than `swap`: during a swap period the browser paints
 * the ligature's fallback text, so an unloaded icon flashes up as the word
 * "package_2". Blocking hides the glyph until the face is ready instead.
 */
const ICON_FONT_HREF =
  "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200" +
  `&icon_names=${ICON_NAMES.join(",")}` +
  "&display=block";

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const { boxFrom } = await getPrices();
  return (
    // `suppressHydrationWarning`: the inline script below adds a class to this
    // element before React hydrates, which is the one intended mismatch.
    <html lang="en-ZA" className={inter.variable} suppressHydrationWarning>
      <head>
        {/*
          Marks the document as scripted before first paint. Scroll-reveal
          start states are scoped to `.js` (see globals.css), so without this
          — no JavaScript, or a crawler that does not run it — nothing on the
          page is ever hidden.
        */}
        <script dangerouslySetInnerHTML={{ __html: "document.documentElement.classList.add('js')" }} />
        {/*
          Warm the font host before the stylesheet below is parsed. The icon
          face is render-blocking, so the two round trips it costs land
          directly on LCP over a mobile connection.
        */}
        <link rel="preconnect" href="https://fonts.googleapis.com" />
        <link rel="preconnect" href="https://fonts.gstatic.com" crossOrigin="" />
        <link rel="stylesheet" href={ICON_FONT_HREF} />
        {/*
          The business identity, on every page — this is what a local search
          result is built from. Page-specific graphs (FAQ, breadcrumbs,
          articles, offers) are emitted by the pages that display them.
        */}
        <JsonLd data={[organizationJsonLd(), localBusinessJsonLd(boxFrom), websiteJsonLd()]} />
      </head>
      <body className="bg-surface font-sans text-on-surface antialiased">
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:fixed focus:left-4 focus:top-4 focus:z-[60] focus:rounded-lg focus:bg-surface-white focus:px-4 focus:py-3 focus:font-semibold focus:text-navy-deep focus:shadow-tactile-md"
        >
          Skip to content
        </a>
        <Navbar />
        <LaunchBar />
        <main id="main" className="pt-[72px]">{children}</main>
        <Footer />
        <RevealObserver />
      </body>
    </html>
  );
}
