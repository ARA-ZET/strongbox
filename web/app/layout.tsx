/**
 * The icon webfont, subsetted to the glyphs the site renders.
 *
 * Unsubsetted this request is 3.97 MB — render-blocking, on every page, and
 * comfortably the heaviest thing the site shipped. `icon_names` brings it to
 * roughly 89 KB. The list is generated by `scripts/collect-icons.mjs`; run it
 * after adding an icon, or the new glyph renders as its own literal name.
 *
 * `display=block` rather than `swap`: during a swap period the browser paints
 * the ligature's fallback text, so an unloaded icon flashes up as the word
 * "package_2". Blocking hides the glyph until the face is ready instead.
 */
const ICON_FONT_HREF =
  "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200" +
  `&icon_names=${ICON_NAMES.join(",")}` +
  "&display=block";

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en-ZA" className={inter.variable}>
      <head>
        {/*
          Warm the font host before the stylesheet below is parsed. The icon
          face is render-blocking, so the two round trips it costs land
          directly on LCP over a mobile connection.
        */}
        <link rel="preconnect" href="https://fonts.googleapis.com" />
        <link rel="preconnect" href="https://fonts.gstatic.com" crossOrigin="" />
        <link rel="stylesheet" href={ICON_FONT_HREF} />
        {/*
          The business identity, on every page — this is what a local search
          result is built from. Page-specific graphs (FAQ, breadcrumbs,
          articles, offers) are emitted by the pages that display them.
        */}
        <JsonLd data={[organizationJsonLd(), localBusinessJsonLd(), websiteJsonLd()]} />
      </head>
      <body className="bg-surface font-sans text-on-surface antialiased">
        <Navbar />
        <main className="pt-[72px]">{children}</main>
        <Footer />
      </body>
    </html>
  );
}
