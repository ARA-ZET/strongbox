/**
 * Collects every Material Symbols ligature the source actually renders.
 *
 * The site loads the icon font from Google Fonts. Unsubsetted, that request is
 * a render-blocking 3.97 MB on every page — the single heaviest thing the site
 * ships. Passing `icon_names` cuts it to the glyphs we use, so this script is
 * the source of truth for that list.
 *
 *   node scripts/collect-icons.mjs          # print the list
 *   node scripts/collect-icons.mjs --check  # exit 1 if lib/icons.ts is stale
 *
 * Two shapes are matched, because those are the two the codebase uses:
 *   <span className="material-symbols-outlined …">home</span>
 *   { icon: "home", … }   in the data modules
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, extname } from "node:path";

const ROOTS = ["app", "components", "lib"];
const SKIP = new Set(["node_modules", ".next"]);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if ([".ts", ".tsx"].includes(extname(entry.name))) out.push(p);
  }
  return out;
}

const icons = new Set();
for (const file of ROOTS.flatMap((r) => walk(r))) {
  const src = readFileSync(file, "utf8");
  // Everything between a material-symbols span's tags. The children are not
  // always a bare ligature — the navbar toggle is `{open ? "close" : "menu"}`,
  // which an element-text-only match silently drops, and a dropped icon
  // renders as its literal name on the page.
  for (const m of src.matchAll(
    /className=(?:"[^"]*|\{`[^`]*)material-symbols-outlined[\s\S]*?>([\s\S]*?)<\/span>/g
  )) {
    const body = m[1];
    for (const lit of body.matchAll(/"([a-z0-9_]+)"|'([a-z0-9_]+)'/g)) {
      icons.add(lit[1] ?? lit[2]);
    }
    const bare = body.trim();
    if (/^[a-z0-9_]+$/.test(bare)) icons.add(bare);
  }
  // Icons carried as data, rendered through {icon} into such a span.
  for (const m of src.matchAll(/\bicon:\s*"([a-z0-9_]+)"/g)) icons.add(m[1]);
}

const list = [...icons].sort();
const generated = `// GENERATED by scripts/collect-icons.mjs — do not edit by hand.
//
// The Material Symbols glyphs this site renders. The full font is 3.97 MB and
// render-blocking; \`app/layout.tsx\` uses this list to request only these,
// which is a few KB. Run \`node scripts/collect-icons.mjs\` after adding an
// icon, or CI's --check will fail the build.
export const ICON_NAMES = ${JSON.stringify(list, null, 2)} as const;
`;

const target = "lib/icons.ts";
if (process.argv.includes("--check")) {
  const current = (() => { try { return readFileSync(target, "utf8"); } catch { return ""; } })();
  if (current !== generated) {
    console.error(`${target} is stale. Run: node scripts/collect-icons.mjs`);
    process.exit(1);
  }
  console.log(`${target} is up to date (${list.length} icons).`);
} else {
  writeFileSync(target, generated);
  console.log(`${target} written — ${list.length} icons:\n${list.join(", ")}`);
}
