import type { Metadata } from "next";
import {
  CONTACT_EMAIL,
  CONTACT_PHONE_HREF,
  SOCIAL_LINKS,
  FAQ_ITEMS,
  HQ_SUBURB,
  HQ_POSTCODE,
  HQ_GEO,
  OPENING_HOURS,
} from "@/lib/constants";
import { REGIONS, type Region } from "@/lib/areas";
import type { Article } from "@/lib/resources";
import type { BoxType } from "@/lib/prices";

/**
 * One source of truth for everything a crawler reads.
 *
 * Before this module the canonical URL was declared once, in the root layout,
 * and Next merges `alternates` shallowly — so every page that did not restate
 * it inherited the homepage's. Eight of the fourteen routes were telling
 * Google they were duplicates of `/` and asking to be dropped from the index.
 * Building metadata through `pageMeta` makes the canonical impossible to
 * forget, because the path is a required argument.
 */
export const SITE_URL = "https://strongbox.co.za";
export const SITE_NAME = "StrongBox Valet Storage";
export const LEGAL_NAME = "StrongBox Valet Storage";

/** Absolute URL for a site-relative path. `""` is the homepage. */
export const url = (path = ""): string => `${SITE_URL}${path}`;

/** The shared social card, generated by `app/opengraph-image.tsx`. */
const OG_IMAGE = {
  url: `${SITE_URL}/opengraph-image`,
  width: 1200,
  height: 630,
  alt: "StrongBox: storage in Cape Town, collected from your door",
};

type PageMetaInput = {
  title: string;
  description: string;
  /** Site-relative, leading slash, no trailing slash. `""` for the homepage. */
  path: string;
  /** Overrides the shared social card title, which defaults to `title`. */
  ogTitle?: string;
  type?: "website" | "article";
  /** ISO date, article pages only. */
  modifiedTime?: string;
  /**
   * A page's own social card, when its segment has an `opengraph-image.tsx`.
   * That file already overrides `og:image`; this keeps `twitter:image` on the
   * same card instead of the shared one.
   */
  image?: { url: string; alt: string };
};

/**
 * Page metadata with the canonical and the social card filled in together.
 *
 * `openGraph` is shallow-merged by Next in the same way `alternates` is, so a
 * page that sets only `title` kept the root layout's OG title — every link
 * shared to WhatsApp unfurled as the homepage regardless of which page was
 * sent. Restating `openGraph` per page is what actually fixes that.
 */
export function pageMeta({
  title,
  description,
  path,
  ogTitle,
  type = "website",
  modifiedTime,
  image,
}: PageMetaInput): Metadata {
  const canonical = url(path);
  const card = image ? { ...OG_IMAGE, ...image } : OG_IMAGE;
  return {
    title,
    description,
    alternates: { canonical },
    openGraph: {
      type,
      locale: "en_ZA",
      siteName: SITE_NAME,
      url: canonical,
      title: ogTitle ?? title,
      description,
      // Stated per page. `openGraph` is replaced, not merged, by a page that
      // sets it, so the shared card has to be named here or it is dropped.
      images: [card],
      ...(modifiedTime ? { modifiedTime } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: ogTitle ?? title,
      description,
      images: [card.url],
    },
  };
}

/* -------------------------------------------------------------------------
 * Structured data
 *
 * Emitted as plain <script type="application/ld+json"> via the `JsonLd`
 * component in `components/JsonLd.tsx`. Every builder returns a plain object
 * so the shapes stay diffable and testable.
 * ---------------------------------------------------------------------- */

/** Stable @id so every graph node can point at the one business. */
const BUSINESS_ID = `${SITE_URL}/#business`;
const ORG_ID = `${SITE_URL}/#organisation`;

/**
 * The city, then its regions, each pointing at the page that lists its
 * suburbs. Listing all ~120 suburbs here put the whole list in the head of
 * every page; the region pages carry them instead. Shared by the business
 * and by each metro-wide service, which cover the same ground.
 */
function metroAreaServed() {
  return [
    { "@type": "City", name: "Cape Town" },
    ...REGIONS.map((r) => ({
      "@type": "Place",
      name: `${r.name}, Cape Town`,
      url: url(`/areas/${r.slug}`),
    })),
  ];
}

/**
 * The trading entity. `SelfStorage` is the closest schema.org type Google
 * recognises for a storage operator; `MovingCompany` is the second type,
 * covering both the collection-and-return half of storage and the mini moves
 * at `/mini-moves`.
 */
export function localBusinessJsonLd(boxFrom: number) {
  return {
    "@context": "https://schema.org",
    "@type": ["SelfStorage", "MovingCompany"],
    "@id": BUSINESS_ID,
    name: SITE_NAME,
    legalName: LEGAL_NAME,
    url: SITE_URL,
    image: url("/opengraph-image"),
    logo: url("/icon.svg"),
    description:
      "Valet storage and mini moves in Cape Town. We collect your belongings from your door, store them in our monitored Kensington facility and return them on request, and move furniture between homes across the metro.",
    telephone: CONTACT_PHONE_HREF.replace("tel:", ""),
    email: CONTACT_EMAIL,
    priceRange: `From R${boxFrom} per month`,
    currenciesAccepted: "ZAR",
    // One facility. `areaServed` below is what carries the rest of the metro —
    // inventing branch addresses to chase suburb searches is what gets a
    // Google Business Profile suspended.
    address: {
      "@type": "PostalAddress",
      addressLocality: HQ_SUBURB,
      addressRegion: "Western Cape",
      postalCode: HQ_POSTCODE,
      addressCountry: "ZA",
    },
    geo: {
      "@type": "GeoCoordinates",
      latitude: HQ_GEO.lat,
      longitude: HQ_GEO.lng,
    },
    areaServed: metroAreaServed(),
    openingHoursSpecification: OPENING_HOURS.map(({ days, opens, closes }) => ({
      "@type": "OpeningHoursSpecification",
      dayOfWeek: days,
      opens,
      closes,
    })),
    sameAs: SOCIAL_LINKS.filter((s) => s.href).map((s) => s.href),
    parentOrganization: { "@id": ORG_ID },
  };
}

export function organizationJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": ORG_ID,
    name: SITE_NAME,
    url: SITE_URL,
    logo: url("/icon.svg"),
    email: CONTACT_EMAIL,
    telephone: CONTACT_PHONE_HREF.replace("tel:", ""),
    sameAs: SOCIAL_LINKS.filter((s) => s.href).map((s) => s.href),
  };
}

export function websiteJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    "@id": `${SITE_URL}/#website`,
    name: SITE_NAME,
    url: SITE_URL,
    inLanguage: "en-ZA",
    publisher: { "@id": ORG_ID },
  };
}

/**
 * Only emit this on pages that visibly render the same `items` — by default
 * `FAQ_ITEMS`, which is what `FAQAccordion` shows. Google treats FAQ markup on
 * a page with no matching answers on screen as a mismatch, and the root
 * layout was shipping it on every route including the legal pages.
 */
export function faqJsonLd(items: readonly { q: string; a: string }[] = FAQ_ITEMS) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map(({ q, a }) => ({
      "@type": "Question",
      name: q,
      acceptedAnswer: { "@type": "Answer", text: a },
    })),
  };
}

/**
 * Breadcrumbs. Home is prepended for you — pass only the trail below it, in
 * order, ending with the current page.
 */
export function breadcrumbJsonLd(trail: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [{ name: "Home", path: "" }, ...trail].map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      item: url(item.path),
    })),
  };
}

export function articleJsonLd(article: Article) {
  const canonical = url(`/resources/${article.slug}`);
  return {
    "@context": "https://schema.org",
    "@type": "Article",
    "@id": `${canonical}#article`,
    headline: article.title,
    description: article.excerpt,
    inLanguage: "en-ZA",
    // The guides carry no per-author byline, so the publisher is the author.
    author: { "@id": ORG_ID },
    publisher: { "@id": ORG_ID },
    // The guide's own header photograph first; the shared card as fallback.
    image: [url(`/photos/${article.photo}-1920.jpg`), OG_IMAGE.url],
    dateModified: article.updated,
    datePublished: article.published,
    mainEntityOfPage: { "@type": "WebPage", "@id": canonical },
    articleSection: article.category,
    timeRequired: `PT${article.readMinutes}M`,
  };
}

/** The service as offered in one region — emitted by `/areas/[slug]`. */
export function regionServiceJsonLd(region: Region, boxFrom: number) {
  const canonical = url(`/areas/${region.slug}`);
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    "@id": `${canonical}#service`,
    name: `Valet storage ${region.where}`,
    serviceType: "Valet storage",
    url: canonical,
    provider: { "@id": BUSINESS_ID },
    areaServed: region.suburbs.map((name) => ({
      "@type": "Place",
      name: `${name}, Cape Town`,
    })),
    offers: {
      "@type": "Offer",
      priceCurrency: "ZAR",
      priceSpecification: {
        "@type": "UnitPriceSpecification",
        minPrice: boxFrom,
        priceCurrency: "ZAR",
        unitCode: "MON",
      },
    },
  };
}

/**
 * The service itself, with the box tiers as offers. Prices are the monthly
 * storage rate; the one-off collection fee is quoted separately and is
 * deliberately not folded in here.
 */
export function serviceJsonLd(boxes: readonly BoxType[]) {
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    serviceType: "Valet storage",
    provider: { "@id": BUSINESS_ID },
    areaServed: { "@type": "City", name: "Cape Town" },
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: "StrongBox storage plans",
      itemListElement: boxes.map((box) => ({
        "@type": "Offer",
        name: box.label,
        description: box.desc,
        price: box.price,
        priceCurrency: "ZAR",
        availability: "https://schema.org/InStock",
        priceSpecification: {
          "@type": "UnitPriceSpecification",
          price: box.price,
          priceCurrency: "ZAR",
          unitCode: "MON",
          billingIncrement: 1,
        },
      })),
    },
  };
}

/**
 * Mini moves as a service — emitted by `/mini-moves`. The three move types
 * are offers without a price: moves are quoted per job, and an invented
 * "from" figure in the markup would be a price the page does not show.
 */
export function movesServiceJsonLd(
  moveTypes: readonly { name: string; body: string }[],
  path: string
) {
  const canonical = url(path);
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    "@id": `${canonical}#service`,
    name: "Mini moves in Cape Town",
    alternateName: ["Small furniture removals", "Mini removals"],
    serviceType: "Furniture removals",
    description:
      "Small, local furniture moves across Cape Town: home to home, into a storage unit of your choice, or split between your new home and StrongBox storage.",
    url: canonical,
    provider: { "@id": BUSINESS_ID },
    areaServed: metroAreaServed(),
    hasOfferCatalog: {
      "@type": "OfferCatalog",
      name: "Mini move options",
      itemListElement: moveTypes.map(({ name, body }) => ({
        "@type": "Offer",
        itemOffered: { "@type": "Service", name, description: body },
      })),
    },
  };
}
